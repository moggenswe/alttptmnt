"""Builds the TMNT PopTracker pack (item tracker with Archipelago autotracking) from the apworld's own tables.

    .venv/Scripts/python.exe tools/make_poptracker_pack.py [--install] [--packs-dir <PopTracker packs folder>]

Writes poptracker/tmnt-ap/ (the pack source, in git) and output/tmnt-ap-poptracker.zip; --install also copies
the zip into PopTracker's packs folder. Item and location IDs come from apworld/tmnt, so the mapping cannot
drift; the images are tools/icons.py's (32x32 pixel art at 2x), each with its grey "-off" variant for items not
found yet.
"""
import argparse
import json
import shutil
import sys
import zipfile
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "Archipelago"))
sys.path.insert(0, str(REPO / "tools"))

from worlds.tmnt.items import AREA_PASSES, TOOLS, TURTLES, item_table  # noqa: E402
from worlds.tmnt.locations import BOSS_LOCATIONS, location_table  # noqa: E402

ICONS = REPO / "tools" / "obs" / "sprites"  # written by tools/icons.py
PACK = REPO / "poptracker" / "tmnt-ap"
ZIP = REPO / "output" / "tmnt-ap-poptracker.zip"
# install.ps1 puts PopTracker in apps\; an older manual install lived in Downloads.
POPTRACKER_PACKS = next((p for p in (REPO / "apps" / "PopTracker-0.36.0" / "packs",
                                     Path.home() / "Downloads" / "PopTracker-0.36.0" / "packs") if p.exists()),
                        REPO / "apps" / "PopTracker-0.36.0" / "packs")
VERSION = "0.1.0"
ITEM_SIZE = 64  # 32x32 icons at exactly 2x, so every pixel stays crisp

TOOL_CODES = {"Missile Pack": "missile", "Rope Pack": "rope", "Zora's Scuba Kit": "scuba"}


def icon(name: str) -> Image.Image:
    return Image.open(ICONS / f"{name}.png").resize((ITEM_SIZE, ITEM_SIZE), Image.NEAREST)


def toggle(name: str, code: str) -> dict:
    return {"name": name, "type": "toggle", "img": f"images/{code}.png", "disabled_img": f"images/{code}-off.png",
            "codes": code}


def build() -> None:
    if PACK.exists():
        shutil.rmtree(PACK)
    for folder in ("images", "items", "layouts", "scripts"):
        (PACK / folder).mkdir(parents=True)

    codes = [turtle.lower() for turtle in TURTLES] + list(TOOL_CODES.values())
    codes += [f"pass{n}" for n in range(1, 6)] + [f"boss{n}" for n in range(1, 6)]
    for code in codes:
        for suffix in ("", "-off"):
            icon(code + suffix).save(PACK / "images" / f"{code}{suffix}.png")

    items = [toggle(turtle, turtle.lower()) for turtle in TURTLES]
    items += [toggle(tool, TOOL_CODES[tool]) for tool in TOOLS]
    items += [toggle(name, f"pass{n}") for n, name in enumerate(AREA_PASSES, start=1)]
    items += [toggle(BOSS_LOCATIONS[n], f"boss{n}") for n in range(1, 6)]
    (PACK / "items" / "items.json").write_text(json.dumps(items, indent=2), encoding="utf-8")

    grid = {"type": "itemgrid", "item_margin": "4,4", "item_size": ITEM_SIZE, "rows": [
        [turtle.lower() for turtle in ("Leonardo", "Raphael", "Michelangelo", "Donatello")],
        list(TOOL_CODES.values()),
        [f"pass{n}" for n in range(1, 6)],
        [f"boss{n}" for n in range(1, 6)],
    ]}
    layouts = {"tracker_default": {"type": "container", "background": "#202c3a", "content": grid},
               "tracker_broadcast": {"type": "container", "background": "#00ff00", "content": grid}}
    (PACK / "layouts" / "tracker.json").write_text(json.dumps(layouts, indent=2), encoding="utf-8")

    manifest = {"name": "TMNT (NES) Archipelago", "game_name": "Teenage Mutant Ninja Turtles",
                "package_version": VERSION, "package_uid": "tmnt_ap", "platform": "nes",
                "author": "tmntalttp", "min_poptracker_version": "0.25.0",
                "variants": {"Item Tracker - AP": {"display_name": "Item Tracker via AP", "flags": ["ap"]}}}
    (PACK / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    item_codes = {turtle: turtle.lower() for turtle in TURTLES} | TOOL_CODES
    item_codes |= {name: f"pass{n}" for n, name in enumerate(AREA_PASSES, start=1)}
    mapping = ["-- Generated by tools/make_poptracker_pack.py from apworld/tmnt; do not edit.", "ITEM_MAPPING = {"]
    mapping += [f"  [{item_table[name][0]}] = \"{code}\",  -- {name}" for name, code in item_codes.items()]
    mapping += ["}", "LOCATION_MAPPING = {"]
    mapping += [f"  [{location_table[BOSS_LOCATIONS[n]]}] = \"boss{n}\",  -- {BOSS_LOCATIONS[n]}" for n in range(1, 6)]
    mapping += ["}", ""]
    (PACK / "scripts" / "mapping.lua").write_text("\n".join(mapping), encoding="utf-8")

    (PACK / "scripts" / "init.lua").write_text(INIT_LUA, encoding="utf-8")
    (PACK / "scripts" / "autotracking.lua").write_text(AUTOTRACKING_LUA, encoding="utf-8")
    (PACK / "README.md").write_text(README, encoding="utf-8")

    ZIP.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(PACK.rglob("*")):
            if path.is_file():
                archive.write(path, path.relative_to(PACK).as_posix())
    print(f"pack -> {PACK}\nzip  -> {ZIP}")


INIT_LUA = """-- TMNT (NES) Archipelago item tracker. Built by tools/make_poptracker_pack.py.
Tracker:AddItems("items/items.json")
Tracker:AddLayouts("layouts/tracker.json")
if Archipelago then
  ScriptHost:LoadScript("scripts/mapping.lua")
  ScriptHost:LoadScript("scripts/autotracking.lua")
end
"""

AUTOTRACKING_LUA = """-- Lights received items and beaten bosses from the Archipelago server (variant "Item Tracker - AP").

local function set(code, active)
  local object = Tracker:FindObjectForCode(code)
  if object then object.Active = active end
end

local function on_clear(slot_data)
  for _, code in pairs(ITEM_MAPPING) do set(code, false) end
  for _, code in pairs(LOCATION_MAPPING) do set(code, false) end
end

local function on_item(index, item_id, item_name, player_number)
  local code = ITEM_MAPPING[item_id]
  if code then set(code, true) end
end

local function on_location(location_id, location_name)
  local code = LOCATION_MAPPING[location_id]
  if code then set(code, true) end
end

Archipelago:AddClearHandler("tmnt clear", on_clear)
Archipelago:AddItemHandler("tmnt item", on_item)
Archipelago:AddLocationHandler("tmnt location", on_location)
"""

README = """# TMNT (NES) Archipelago - PopTracker pack

Item tracker for the TMNT slot of the ALttP + TMNT Archipelago seed: the four turtles, Missile Pack, Rope Pack,
Zora's Scuba Kit, the five sewer passes and the five Area bosses (3 needed for the Technodrome).
Variant "Item Tracker - AP" lights everything from the Archipelago server.

Built by tools/make_poptracker_pack.py in https://github.com/moggenswe/alttptmnt; the icons were made with
ChatGPT for the project and turned into 32x32 pixel art by tools/icons.py. The characters belong to their owners.
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--install", action="store_true", help="copy the zip into PopTracker's packs folder")
    parser.add_argument("--packs-dir", type=Path, default=POPTRACKER_PACKS, help="PopTracker's packs folder")
    args = parser.parse_args()
    build()
    if args.install:
        args.packs_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy(ZIP, args.packs_dir / ZIP.name)
        print(f"installed -> {args.packs_dir / ZIP.name}")
